// Online tests live in `src/commonOnlineTest/kotlin` and are stitched into the
// canonical `jvmTest` compilation via `kotlin.srcDir(...)`. They carry
// `@EnabledIfSystemProperty(named = "routex.online", matches = "true")` so the
// standard `:check` `jvmTest` task skips them at runtime; `:jvmOnlineTest` sets
// the property to run them, and IntelliJ's per-test gutter (which goes through
// `:jvmTest --tests "..."`) auto-enables the property when an explicit test
// filter is present.
val commonOnlineTestSrc: String = "src/commonOnlineTest/kotlin"

// Bake the library's own version into commonMain so [RoutexClientCore] can emit it as
// the `yaxi-client-version` HTTP header without exposing a meaningless caller-provided
// parameter. The constant lives in `:settlement` because [RoutexClientCore] (its single
// consumer) lives here.
val generatedVersionDir = layout.buildDirectory.dir("generated/routex/commonMain/kotlin")
val generateRoutexVersion =
    tasks.register("generateRoutexVersion") {
        val versionValue = providers.provider { project.version.toString() }
        val outputDir = generatedVersionDir
        inputs.property("version", versionValue)
        outputs.dir(outputDir)
        doLast {
            val dir = outputDir.get().asFile.resolve("tech/yaxi/routex/settlement/generated")
            dir.mkdirs()
            dir.resolve("Version.kt").writeText(
                """
                // Generated by gradle. Do not edit.
                package tech.yaxi.routex.settlement.generated

                internal const val ROUTEX_CLIENT_VERSION: String = "${versionValue.get()}"
                """.trimIndent() + "\n",
            )
        }
    }

